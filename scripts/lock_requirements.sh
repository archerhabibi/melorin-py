#!/usr/bin/env bash
# Re-generate the hash-locked Python requirements (audit W17: reproducible, tamper-evident installs).
#
#   scripts/lock_requirements.sh            # re-lock everything in place
#   scripts/lock_requirements.sh --upgrade  # also move every dependency to the newest allowed version
#   scripts/lock_requirements.sh --check    # CI: fail if a *.in file and its lock disagree (writes nothing)
#
# Inputs  (edit these):  apps/api/requirements.in, apps/api/requirements-dev.in,
#                        apps/telegram-main/requirements.in, apps/telegram-reseller/requirements.in
# Outputs (generated):   the matching requirements*.txt, every transitive dependency pinned with --hash entries.
# Images install them with `pip install --require-hashes`. The lock is resolved for the Python the images run (3.12) and for
# every platform (--universal), so it does not depend on the machine that runs this script. Needs `uv` (pip install uv).
# --check compares the pinned name==version set only, so a hash added upstream for an existing release never fails CI.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PYVER="${LOCK_PYTHON_VERSION:-3.12}"
MODE="lock"; EXTRA=()
case "${1:-}" in
  --upgrade) EXTRA+=(--upgrade) ;;
  --check) MODE="check" ;;
  "") ;;
  *) echo "usage: $0 [--upgrade|--check]" >&2; exit 2 ;;
esac
command -v uv >/dev/null || { echo "uv is required: pip install uv" >&2; exit 1; }

WORK="$ROOT"
if [ "$MODE" = check ]; then
  WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
  for d in apps/api apps/telegram-main apps/telegram-reseller; do
    mkdir -p "$WORK/$d"; cp "$ROOT/$d"/requirements*.in "$ROOT/$d"/requirements*.txt "$WORK/$d/"
  done
fi

lock() { # lock <dir> <in-file> <out-file> [extra uv args...]
  local dir="$1" in="$2" out="$3"; shift 3
  ( cd "$WORK/$dir" && uv pip compile "$in" -o "$out" --generate-hashes --universal --python-version "$PYVER" \
      --no-header --quiet "${EXTRA[@]}" "$@" )
  { printf '# GENERATED by scripts/lock_requirements.sh from %s - do not edit by hand (Python %s, all platforms).\n' "$in" "$PYVER"
    cat "$WORK/$dir/$out"; } > "$WORK/$dir/$out.tmp" && mv "$WORK/$dir/$out.tmp" "$WORK/$dir/$out"
}

lock apps/api requirements.in requirements.txt
# the dev set is constrained by the runtime lock so tests exercise exactly the versions the image ships
lock apps/api requirements-dev.in requirements-dev.txt -c requirements.txt
lock apps/telegram-main requirements.in requirements.txt
lock apps/telegram-reseller requirements.in requirements.txt

if [ "$MODE" = check ]; then
  pins() { grep -E '^[A-Za-z0-9_.-]+(\[[^]]*\])?==' "$1" | sed 's/ .*//' | sort; }
  bad=0
  for f in apps/api/requirements.txt apps/api/requirements-dev.txt apps/telegram-main/requirements.txt apps/telegram-reseller/requirements.txt; do
    if ! diff <(pins "$ROOT/$f") <(pins "$WORK/$f") >/dev/null; then
      echo "STALE LOCK: $f does not match its .in file. Run scripts/lock_requirements.sh and commit the result." >&2
      diff <(pins "$ROOT/$f") <(pins "$WORK/$f") >&2 || true; bad=1
    fi
  done
  [ "$bad" = 0 ] && echo "lock files are current"
  exit "$bad"
fi
echo "locked: apps/api/requirements{,-dev}.txt apps/telegram-main/requirements.txt apps/telegram-reseller/requirements.txt"
